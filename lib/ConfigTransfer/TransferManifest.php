<?php

declare(strict_types=1);

/**
 * AudioCheck transfer manifest — every appconfig key and every
 * ac_* table classified exactly once
 * (gate: scripts/check-config-transfer-manifest.py).
 *
 * Access door is app-local appconfig (no platform restriction mirror) —
 * the door keys are still 'mirrored' class because the
 * restricted-door-requires-allowlist invariant is cross-key: they land in
 * ONE atomic AccessControlService::saveAppPolicy call via writeMirrored,
 * never raw setAppValue (NN-02, azc #46 class).
 */

namespace OCA\AudioCheck\ConfigTransfer;

final class TransferManifest extends AbstractTransferManifest
{
	private const SCHEMA_VERSION = 1;

	public function schemaVersion(): int
	{
		return self::SCHEMA_VERSION;
	}

	/** @return array<string,array> */
	public function keys(): array
	{
		return self::normaliseKeys([
			// ── access door / admin policy — written atomically through
			// AccessControlService::saveAppPolicy (never raw setAppValue;
			// the restricted-door-requires-allowlist invariant is cross-key) ──
			'access_restriction_enabled' => ['class' => 'mirrored', 'security' => true, 'section' => 'access'],
			'access_allowed_user_ids' => ['class' => 'mirrored', 'security' => true, 'refs' => ['kind' => 'uid_list_json'], 'section' => 'access'],
			'access_allowed_group_ids' => ['class' => 'mirrored', 'security' => true, 'refs' => ['kind' => 'gid_list_json'], 'section' => 'access'],
			'app_admin_user_ids' => ['class' => 'mirrored', 'security' => true, 'refs' => ['kind' => 'uid_list_json'], 'section' => 'admins'],
			// ── new-user defaults (Settings → Defaults) ──
			'default_library_folder' => ['class' => 'plain', 'section' => 'defaults'],
			'max_meta_temp_mb' => ['class' => 'plain', 'section' => 'defaults'],
			// ── foreign appconfig — read-only core key
			// (ScanService reads core's 'backgroundjobs_mode' to decide the
			// ajax-cron tick; it is never written by this app, never ours
			// to transfer) ──
			'backgroundjobs_mode' => 'internal',
			// ── internal bookkeeping — never transferred ──
			// CAS token for the policy save path — instance-local, must not
			// be overwritten by a file's snapshot of the source counter.
			'app_policy_version' => 'internal',
			'uninstall_repair_pass' => 'internal',
			'upgrade_backup_last_snapshot_id' => 'internal',
			'upgrade_backup_max_snapshots' => 'internal',
			'transfer_receipts' => 'internal',
			'transfer_job_state' => 'internal',
			'transfer_last_import_at' => 'internal',
		]);
	}

	/** @return array<string,array> */
	public function tables(): array
	{
		return self::normaliseTables([
			// ══ user-scoped state — only for users on both instances (D1) ══
			// root_file_id is the resolved NC fileid of the library root —
			// instance-bound, nullable → env-dropped; the next scan on the
			// target re-resolves it from folder_path (the portable identity
			// — the unique index on (user_id, root_file_id) cannot anchor a
			// transfer because the id does not exist there).
			'ac_libraries' => ['class' => 'user-data', 'strategy' => 'upsert-natural-key',
				'natural_key' => ['user_id', 'folder_path'],
				'uid_ref' => ['user_id'],
				'env_columns' => ['root_file_id']],
			// cover_file_id is an NC fileid — nullable → env-dropped; the
			// cover falls back to "none" on the target (bc_tx_attachments
			// class: blobs under appdata have no import path).
			'ac_playlists' => ['class' => 'user-data', 'strategy' => 'upsert-natural-key',
				'natural_key' => ['user_id', 'name'],
				'uid_ref' => ['user_id'],
				'env_columns' => ['cover_file_id']],

			// ══ derived / internal — NEVER transferred ══
			// Scan products keyed by NC file_id — the ids are instance-bound
			// and the columns are NOT NULL, so no row can be env-dropped;
			// the scanner rebuilds the whole index on the target.
			'ac_file_meta' => ['class' => 'derived'],
			'ac_tracks' => ['class' => 'derived'],
			// Playlist membership + playback state point at NC file_ids —
			// real user data but with no portable identity (no path column);
			// transferred rows would dangle on the target.
			'ac_playlist_items' => ['class' => 'internal'],
			'ac_play_state' => ['class' => 'internal'],
			// Play queue is ephemeral session state (items are file-bound).
			'ac_queue' => ['class' => 'internal'],
			'ac_queue_items' => ['class' => 'internal'],
			// Scanner cursor/status per user — regenerated by the next scan.
			'ac_scan_state' => ['class' => 'internal'],
			// Rate-limiter buckets — instance-local abuse protection state.
			'ac_rate_limits' => ['class' => 'internal'],
		]);
	}
}
